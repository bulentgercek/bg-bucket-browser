export type EntryGlyph = keyof typeof GLYPHS;

/** An entry's icon. A plain function rather than a component, like the other
    glyph helpers: one more component per row is another thing a long list has
    to run through on every redraw. */
export function entryIcon(glyph: EntryGlyph, size: number, className: string) {
  const { icon: Glyph, fill } = GLYPHS[glyph];
  // Children are drawn before the outline, so the fill sits under it.
  return (
    <Glyph size={size} className={`shrink-0 ${className}`}>
      <path d={fill} opacity={0.2} />
    </Glyph>
  );
}
